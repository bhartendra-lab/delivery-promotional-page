/**
 * Best-effort match of a Google Places `administrative_area_level_1.long_name`
 * against the GST state list, for pre-selecting (never silently committing)
 * the state dropdown from a freshly-searched address.
 */
export function findGstStateByName(name: string | undefined): { code: string; name: string } | null {
  if (!name) return null;
  const normalized = name.trim().toLowerCase();
  return GST_STATE_CODES.find((s) => s.name.toLowerCase() === normalized) ?? null;
}
